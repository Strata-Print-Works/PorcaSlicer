#!/usr/bin/env python3
"""Generate native constants from the supplied Porca design-system tokens."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
data = json.loads((root / 'resources/design-system/tokens.json').read_text())
colors = {item['name']: item['value'] for item in data['color']['tokens']}
def resolve(name, theme):
    value = colors[name][theme]
    return resolve(value[1:-1], theme) if value.startswith('{') else value
def native_color(value):
    if value.startswith('rgba('):
        r, g, b, alpha = [float(x) for x in value[5:-1].split(',')]
        return f'#{int(r):02X}{int(g):02X}{int(b):02X}', round(alpha * 255)
    return value, 255

def pascal(name):
    return ''.join(part.capitalize() for part in name.split('-'))
lines = ['// Generated by scripts/generate_design_tokens.py; edit tokens.json instead.', '#pragma once', '', '#include <array>', '#include <cstddef>', '', 'namespace Slic3r::GUI::DesignSystem {', 'enum class ColorRole {']
lines += ['    ' + pascal(name) + ',' for name in colors]
lines += ['};', 'struct ColorToken { const char* dark; const char* light; unsigned char dark_alpha; unsigned char light_alpha; };', f'inline constexpr std::array<ColorToken, {len(colors)}> colors{{{{']
for name in colors:
    dark, dark_alpha = native_color(resolve(name, 'dark'))
    light, light_alpha = native_color(resolve(name, 'light'))
    lines.append(f'    {{{json.dumps(dark)}, {json.dumps(light)}, {dark_alpha}, {light_alpha}}},')
lines += ['}};', 'constexpr const char* color_hex(ColorRole role, bool dark)', '{', '    const auto& token = colors[static_cast<std::size_t>(role)];', '    return dark ? token.dark : token.light;', '}', 'constexpr unsigned char color_alpha(ColorRole role, bool dark)', '{', '    const auto& token = colors[static_cast<std::size_t>(role)];', '    return dark ? token.dark_alpha : token.light_alpha;', '}', '']
for group in ('spacing','radius','size'):
    lines += [f'inline constexpr int {item["name"].replace("-","_")} = {item["value"].removesuffix("px")};' for item in data[group]['tokens']]
styles = [(group['family'], style) for group in data['type']['groups'] for style in group['styles']]
lines += ['', 'enum class TypeStyle { ' + ', '.join(pascal(style['name']) for _,style in styles) + ' };', 'struct TypeToken { const char* family; double size; double line_height; int weight; };', f'inline constexpr std::array<TypeToken, {len(styles)}> type_styles{{{{']
families={'sans':'Figtree','display':'Nunito','mono':'JetBrains Mono'}
lines += [f'    {{"{families[family]}", {style["fontSize"].removesuffix("px")}.0, {style["lineHeight"].removesuffix("px")}.0, {style["fontWeight"]}}},' for family,style in styles]
lines += ['}};', 'constexpr const TypeToken& type_token(TypeStyle style) { return type_styles[static_cast<std::size_t>(style)]; }', '', '} // namespace Slic3r::GUI::DesignSystem', '']
(root / 'src/slic3r/GUI/DesignTokens.hpp').write_text('\n'.join(lines))
